export const getDemoUser = (role: UserRole, name?: string, email?: string): User => {
  const existing = demoUsers.find((user) => user.role === role);
  const fallback: User = {
    id: `demo-${role}`,
    name: name || "Demo teammate",
    email: email || "demo@punchpoint.demo",
    role,
    initials: "DT",
    team: "Product design",
  };
  return {
    ...(existing ?? fallback),
    ...(name
      ? {
          name,
          initials: name
            .split(" ")
            .map((part) => part[0])
            .join("")
            .slice(0, 2)
            .toUpperCase(),
        }
      : {}),
    ...(email ? { email } : {}),
  };
};

